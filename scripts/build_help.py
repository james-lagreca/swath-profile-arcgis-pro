# -*- coding: utf-8 -*-
"""Generate the tool's metadata side-car from ``tools/help_text.py``.

ArcGIS Pro shows parameter help from ``SwathProfile.SwathProfileTool.pyt.xml``
next to the toolbox.  The element layout follows Esri's own tool documents:
``<Esri>`` block, then ``<tool>`` holding ``<parameters>`` with one ``<param>``
per parameter each carrying a ``<dialogReference>``, then ``<summary>``.

Run with the ArcGIS Pro interpreter after changing parameters or help text::

    "C:\\Program Files\\ArcGIS\\Pro\\bin\\Python\\envs\\arcgispro-py3\\python.exe" scripts\\build_help.py
"""

from __future__ import annotations

import datetime
import os
import sys
import xml.etree.ElementTree as ET
from importlib.machinery import SourceFileLoader

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from tools.help_text import PARAM_HELP, TOOL_SUMMARY, TOOL_USAGE  # noqa: E402

#: arcpy datatype keyword -> the display name Esri metadata uses.
DATATYPE_NAMES = {
    "GPFeatureRecordSetLayer": "Feature Set",
    "GPFeatureLayer": "Feature Layer",
    "Field": "Field",
    "GPRasterLayer": "Raster Layer",
    "GPLinearUnit": "Linear Unit",
    "DETable": "Table",
    "GPString": "String",
    "GPLong": "Long",
    "GPDouble": "Double",
    "GPBoolean": "Boolean",
    "DEFeatureClass": "Feature Class",
    "DEFolder": "Folder",
    "DEFile": "File",
}


def _para(parent, text):
    el = ET.SubElement(parent, "para")
    el.text = text
    return el


def build_tool_xml(tool, toolbox_alias="swathprofile"):
    now = datetime.datetime.now()
    root = ET.Element("metadata", {"xml:lang": "en"})
    esri = ET.SubElement(root, "Esri")
    ET.SubElement(esri, "CreaDate").text = now.strftime("%Y%m%d")
    ET.SubElement(esri, "CreaTime").text = now.strftime("%H%M%S00")
    ET.SubElement(esri, "ArcGISFormat").text = "1.0"
    ET.SubElement(esri, "SyncOnce").text = "TRUE"
    ET.SubElement(esri, "ModDate").text = now.strftime("%Y%m%d")
    ET.SubElement(esri, "ModTime").text = now.strftime("%H%M%S")

    tool_el = ET.SubElement(root, "tool", {
        "name": type(tool).__name__,
        "displayname": tool.label,
        "toolboxalias": toolbox_alias,
        "xmlns": "",
    })
    ET.SubElement(tool_el, "arcToolboxHelpPath").text = \
        r"c:\program files\arcgis\pro\Resources\Help\gp"

    params_el = ET.SubElement(tool_el, "parameters")
    missing = []
    for prm in tool.getParameterInfo():
        dtype = DATATYPE_NAMES.get(prm.datatype, prm.datatype)
        if getattr(prm, "multiValue", False):
            dtype = "Multiple Value"
        optional = prm.parameterType == "Optional"
        expr = prm.name if not getattr(prm, "multiValue", False) \
            else f"{prm.name};{prm.name}..."
        if optional:
            expr = "{" + expr + "}"
        p_el = ET.SubElement(params_el, "param", {
            "name": prm.name,
            "displayname": prm.displayName,
            "type": prm.parameterType,
            "direction": prm.direction,
            "datatype": dtype,
            "expression": expr,
        })
        help_entry = PARAM_HELP.get(prm.name)
        if help_entry is None:
            missing.append(prm.name)
            continue
        summary, paragraphs, bullets = help_entry
        ref = ET.SubElement(p_el, "dialogReference")
        _para(ref, summary)
        for text in paragraphs:
            _para(ref, text)
        if bullets:
            lst = ET.SubElement(ref, "bulletList")
            for text in bullets:
                ET.SubElement(lst, "bullet_item").text = text
        # The Python reference shows in the tool's help page.
        pref = ET.SubElement(p_el, "pythonReference")
        _para(pref, summary)

    summary_el = ET.SubElement(tool_el, "summary")
    _para(summary_el, TOOL_SUMMARY)
    usage_el = ET.SubElement(tool_el, "usage")
    for text in TOOL_USAGE:
        _para(usage_el, text)

    data = ET.SubElement(root, "dataIdInfo")
    cit = ET.SubElement(data, "idCitation")
    ET.SubElement(cit, "resTitle").text = tool.label
    ET.SubElement(data, "idAbs").text = TOOL_SUMMARY
    return root, missing


def build_parameters_md(tool):
    """Markdown parameter reference, from the same text the dialog shows."""
    lines = ["# Swath Profile — parameters", "",
             "Generated by `scripts/build_help.py` from `tools/help_text.py`; the "
             "same text appears when you hover a parameter in ArcGIS Pro.", "",
             TOOL_SUMMARY, ""]
    for text in TOOL_USAGE:
        lines.append(f"- {text}")
    lines.append("")
    current = None
    for prm in tool.getParameterInfo():
        cat = getattr(prm, "category", None) or "Main"
        if cat != current:
            lines += [f"## {cat}", ""]
            current = cat
        summary, paragraphs, bullets = PARAM_HELP.get(prm.name, ("", [], []))
        req = "required" if prm.parameterType == "Required" else "optional"
        lines.append(f"### {prm.displayName}  \n`{prm.name}` · {req}")
        lines.append("")
        lines.append(summary)
        for text in paragraphs:
            lines += ["", text]
        if bullets:
            lines.append("")
            lines += [f"- {b}" for b in bullets]
        lines.append("")
    return "\n".join(lines)


def main():
    pyt = os.path.join(ROOT, "SwathProfile.pyt")
    module = SourceFileLoader("swathprofile_pyt", pyt).load_module()
    toolbox = module.Toolbox()
    written = []
    for tool_cls in toolbox.tools:
        tool = tool_cls()
        root, missing = build_tool_xml(tool, toolbox.alias)
        if missing:
            raise SystemExit(f"Help text missing for parameters: {missing}")
        ET.indent(root, space="    ")
        out = os.path.join(ROOT, f"SwathProfile.{tool_cls.__name__}.pyt.xml")
        with open(out, "w", encoding="utf-8") as fh:
            fh.write('<?xml version="1.0" encoding="UTF-8"?>\n')
            fh.write(ET.tostring(root, encoding="unicode"))
        written.append(out)
        md = os.path.join(ROOT, "docs", "PARAMETERS.md")
        with open(md, "w", encoding="utf-8") as fh:
            fh.write(build_parameters_md(tool))
        written.append(md)
    for path in written:
        print("wrote", path)


if __name__ == "__main__":
    main()
